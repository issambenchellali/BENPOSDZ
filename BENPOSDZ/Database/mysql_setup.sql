-- ============================================================
-- BENPOS DZ — إعداد قاعدة البيانات والمستخدم بأمان (وضع LAN)
-- ------------------------------------------------------------
-- طريقة التنفيذ:
--   أ) MySQL Workbench: افتح اتصال root ثم انسخ الكل ونفّذه.
--   ب) أو من موجه الأوامر:
--        mysql -u root -p < mysql_setup.sql
--
-- مهم: البرنامج ينشئ الجداول تلقائياً عند أول تشغيل.
-- ============================================================

-- 1) إنشاء قاعدة البيانات بترميز عربي كامل
CREATE DATABASE IF NOT EXISTS benposdb
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

-- 2) مستخدم محلي: يسمح فقط لجهاز الخادم نفسه (الأكثر أماناً)
CREATE USER IF NOT EXISTS 'benpos_user'@'localhost' IDENTIFIED BY 'StrongPos123!';

-- 3) مستخدم للشبكة المحلية: يسمح فقط للأجهزة التي تبدأ عناوينها بـ 192.168
--    (أجهزة المحل داخل نفس الشبكة فقط — لا يمكن لأي جهاز خارجي الاتصال)
CREATE USER IF NOT EXISTS 'benpos_user'@'192.168.%' IDENTIFIED BY 'StrongPos123!';

-- ⚠️ تحذير أمني: لا تستخدم أبداً 'benpos_user'@'%'
--    لأن ذلك يسمح لأي جهاز في أي مكان على الإنترنت بمحاولة الدخول
--    إلى منفذ 3306 إذا كان المنفذ مفتوحاً في الراوتر.

-- 4) منح الصلاحيات الكاملة على قاعدة البيانات فقط
GRANT ALL PRIVILEGES ON benposdb.* TO 'benpos_user'@'localhost';
GRANT ALL PRIVILEGES ON benposdb.* TO 'benpos_user'@'192.168.%';

FLUSH PRIVILEGES;

-- ============================================================
-- إعدادات إضافية موصى بها في ملف my.ini الخاص بـ MySQL:
-- ------------------------------------------------------------
-- [mysqld]
-- bind-address = 0.0.0.0
-- skip-networking = 0
-- max_connections = 100
-- ------------------------------------------------------------
-- بعد التعديل أعد تشغيل خدمة MySQL: (Services -> MySQL -> Restart)
-- ============================================================

-- 🔥 إجراءات أمنية إلزامية بعد التثبيت:
--  1) غيّر كلمة مرور المستخدم benpos_user من هذا السكريبت
--     قبل تسليم البرنامج للزبون.
--  2) من داخل إعدادات الراوتر: أغلق المنفذ 3306 للإنترنت
